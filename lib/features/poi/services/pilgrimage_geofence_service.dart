import 'dart:async';

import '../../../core/database/database.dart';
import '../../../core/utils/geodesic_math.dart';
import '../models/proximity_event.dart';
import 'spatial_grid_index.dart';

/// Background-capable geofencing and proximity perception engine for anime pilgrimage spots.
///
/// Features:
/// - O(1) candidate lookup via [SpatialGridIndex] before calculating exact Haversine distance.
/// - Dual-radius hysteresis buffer (enter radius vs exit radius) to prevent alert flutter at spot boundaries.
/// - Configurable cooldown per spot to avoid notification spam.
/// - Emits real-time [ProximityEvent] stream with distance, compass bearing, and anime metadata.
class PilgrimageGeofenceService {
  final GeofenceConfig config;
  final SpatialGridIndex<TrackedStopState> _spatialIndex;
  final Map<String, TrackedStopState> _trackedStops = {};
  final StreamController<ProximityEvent> _eventController =
      StreamController<ProximityEvent>.broadcast();

  bool _isDisposed = false;

  PilgrimageGeofenceService({
    this.config = const GeofenceConfig(),
    double spatialCellSize = 0.005,
  }) : _spatialIndex = SpatialGridIndex<TrackedStopState>(cellSize: spatialCellSize);

  /// Stream of proximity enter/exit events.
  Stream<ProximityEvent> get eventStream => _eventController.stream;

  /// List of stops the user is currently located inside the geofence of.
  List<TrackedStopState> get activeInsideStops =>
      _trackedStops.values.where((s) => s.isInside).toList();

  /// Total number of spots currently tracked in the geofence engine.
  int get trackedCount => _trackedStops.length;

  /// Registers multiple [stops] for proximity tracking.
  void registerStops(
    Iterable<Stop> stops, {
    Map<String, String>? animeByStopId,
  }) {
    for (final stop in stops) {
      registerStop(stop, animeName: animeByStopId?[stop.id]);
    }
  }

  /// Registers a single [stop] for proximity tracking.
  void registerStop(Stop stop, {String? animeName}) {
    final existing = _trackedStops[stop.id];
    final state = TrackedStopState(
      stopId: stop.id,
      placeKey: stop.placeKey,
      stopName: stop.name,
      lat: stop.lat,
      lng: stop.lng,
      animeName: animeName,
      coverUrl: stop.coverRemoteUrl,
      isInside: existing?.isInside ?? false,
      lastEnteredAt: existing?.lastEnteredAt,
      lastExitedAt: existing?.lastExitedAt,
    );

    _trackedStops[stop.id] = state;
    _spatialIndex.insert(stop.lat, stop.lng, state);
  }

  /// Removes a stop from active geofence tracking.
  void unregisterStop(String stopId) {
    _trackedStops.remove(stopId);
    // Rebuild spatial index with remaining stops
    _spatialIndex.clear();
    for (final state in _trackedStops.values) {
      _spatialIndex.insert(state.lat, state.lng, state);
    }
  }

  /// Clears all tracked spots.
  void clearStops() {
    _trackedStops.clear();
    _spatialIndex.clear();
  }

  /// Evaluates user GPS fix ([userLat], [userLng]) and triggers enter/exit events.
  ///
  /// Returns all [ProximityEvent]s generated by this fix.
  List<ProximityEvent> processLocationUpdate(
    double userLat,
    double userLng, {
    DateTime? timestamp,
  }) {
    if (_isDisposed) return const [];
    final now = timestamp ?? DateTime.now();
    final events = <ProximityEvent>[];

    // 1. Query candidate stops from the spatial grid index within exit radius
    final candidates = _spatialIndex.queryCandidates(
      userLat,
      userLng,
      radiusMeters: config.exitRadiusMeters,
    );

    final candidateStopIds = <String>{};

    for (final cand in candidates) {
      final state = cand.item;
      candidateStopIds.add(state.stopId);

      final dist = GeodesicMath.haversineDistance(
        userLat,
        userLng,
        state.lat,
        state.lng,
      );

      final bearing = GeodesicMath.bearingDegrees(
        userLat,
        userLng,
        state.lat,
        state.lng,
      );
      final compass = GeodesicMath.bearingToCompass(bearing);

      if (!state.isInside) {
        // Check for enter event
        if (dist <= config.enterRadiusMeters) {
          final isCoolingDown = state.lastEnteredAt != null &&
              now.difference(state.lastEnteredAt!) < config.cooldownDuration;

          if (!isCoolingDown) {
            state.isInside = true;
            state.lastEnteredAt = now;

            final event = ProximityEvent(
              eventType: ProximityEventType.enter,
              stopId: state.stopId,
              placeKey: state.placeKey,
              stopName: state.stopName,
              distanceMeters: dist,
              bearingDegrees: bearing,
              bearingCompass: compass,
              animeName: state.animeName,
              coverUrl: state.coverUrl,
              stopLat: state.lat,
              stopLng: state.lng,
              userLat: userLat,
              userLng: userLng,
              timestamp: now,
            );
            events.add(event);
            if (!_eventController.isClosed) _eventController.add(event);
          }
        }
      } else {
        // Currently inside: check for exit event (hysteresis)
        if (dist > config.exitRadiusMeters) {
          state.isInside = false;
          state.lastExitedAt = now;

          final event = ProximityEvent(
            eventType: ProximityEventType.exit,
            stopId: state.stopId,
            placeKey: state.placeKey,
            stopName: state.stopName,
            distanceMeters: dist,
            bearingDegrees: bearing,
            bearingCompass: compass,
            animeName: state.animeName,
            coverUrl: state.coverUrl,
            stopLat: state.lat,
            stopLng: state.lng,
            userLat: userLat,
            userLng: userLng,
            timestamp: now,
          );
          events.add(event);
          if (!_eventController.isClosed) _eventController.add(event);
        }
      }
    }

    // 2. Check any currently active stops that were not in candidates (e.g. rapid movement or teleport)
    for (final state in _trackedStops.values) {
      if (state.isInside && !candidateStopIds.contains(state.stopId)) {
        final dist = GeodesicMath.haversineDistance(
          userLat,
          userLng,
          state.lat,
          state.lng,
        );
        if (dist > config.exitRadiusMeters) {
          state.isInside = false;
          state.lastExitedAt = now;

          final bearing = GeodesicMath.bearingDegrees(
            userLat,
            userLng,
            state.lat,
            state.lng,
          );
          final compass = GeodesicMath.bearingToCompass(bearing);

          final event = ProximityEvent(
            eventType: ProximityEventType.exit,
            stopId: state.stopId,
            placeKey: state.placeKey,
            stopName: state.stopName,
            distanceMeters: dist,
            bearingDegrees: bearing,
            bearingCompass: compass,
            animeName: state.animeName,
            coverUrl: state.coverUrl,
            stopLat: state.lat,
            stopLng: state.lng,
            userLat: userLat,
            userLng: userLng,
            timestamp: now,
          );
          events.add(event);
          if (!_eventController.isClosed) _eventController.add(event);
        }
      }
    }

    return events;
  }

  /// Disposes stream controllers and releases listeners.
  void dispose() {
    _isDisposed = true;
    _eventController.close();
  }
}
